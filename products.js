window.getProduct = function getProduct(id) {
  return window.PRODUCTS.find((item) => item.id === id) || null;
};

window.productHref = function productHref(id) {
  return "producto.html?id=" + encodeURIComponent(id);
};

window.productImage = function productImage(id) {
  const product = window.getProduct(id);
  if (!product) return "";
  if (product.images && product.images[0]) return product.images[0].src;
  return product.image || "";
};
